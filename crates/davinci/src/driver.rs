//! The Windows driver side: what the instrument is bound to, and how to move it
//! to WinUSB without asking the user to install anything by hand.
//!
//! Why this exists: the Hantek 1008C ships with a 2017 WDM driver (`DSO6CDE`)
//! whose kernel code does not survive direct access — it bugchecks the machine
//! with `0x3B`. Our program therefore needs the device bound to the generic
//! `WinUSB` driver, where nothing vendor-supplied runs in the kernel.
//!
//! Binding a device to WinUSB normally takes a signed driver package. We carry
//! one: `driver/ydj-2088.{inf,cat}` plus the public certificate its catalog was
//! signed with (see `driver/README.md` for where those bytes came from). The
//! install is three commands — trust the certificate, add the package, rescan —
//! and everything happens after a single UAC prompt.
//!
//! This module never touches the device itself; it only reports on it and, when
//! asked, installs the driver.

#![cfg(windows)]

use std::ffi::c_void;

use std::process::Command;
use std::ptr;

type Handle = *mut c_void;

const VID_PID: &str = "VID_0783&PID_5725";
const WANT_SERVICE: &str = "WinUSB";

// Embedded so the program has no side files to lose.
const DRIVER_INF: &[u8] = include_bytes!("../../../driver/ydj-2088.inf");
const DRIVER_CAT: &[u8] = include_bytes!("../../../driver/ydj-2088.cat");
const DRIVER_CER: &[u8] = include_bytes!("../../../driver/libwdi-autogenerated.cer");

const DIGCF_PRESENT: u32 = 0x02;
const DIGCF_ALLCLASSES: u32 = 0x04;

const SPDRP_DEVICEDESC: u32 = 0x00;
const SPDRP_HARDWAREID: u32 = 0x01;
const SPDRP_SERVICE: u32 = 0x04;
const SPDRP_CLASS: u32 = 0x07;
const SPDRP_FRIENDLYNAME: u32 = 0x0C;

#[repr(C)]
#[derive(Clone, Copy)]
struct Guid {
    data1: u32,
    data2: u16,
    data3: u16,
    data4: [u8; 8],
}

#[repr(C)]
struct SpDevInfoData {
    cb_size: u32,
    class_guid: Guid,
    dev_inst: u32,
    reserved: usize,
}

#[link(name = "setupapi")]
extern "system" {
    fn SetupDiGetClassDevsW(class: *const Guid, enumr: *const u16, parent: Handle, flags: u32) -> Handle;
    fn SetupDiEnumDeviceInfo(set: Handle, index: u32, info: *mut SpDevInfoData) -> i32;
    fn SetupDiGetDeviceRegistryPropertyW(
        set: Handle,
        info: *mut SpDevInfoData,
        property: u32,
        reg_type: *mut u32,
        buffer: *mut u8,
        size: u32,
        needed: *mut u32,
    ) -> i32;
    fn SetupDiGetDeviceInstanceIdW(
        set: Handle,
        info: *mut SpDevInfoData,
        buffer: *mut u16,
        size: u32,
        needed: *mut u32,
    ) -> i32;
    fn SetupDiDestroyDeviceInfoList(set: Handle) -> i32;
}

#[link(name = "cfgmgr32")]
extern "system" {
    fn CM_Get_DevNode_Status(status: *mut u32, problem: *mut u32, dev_inst: u32, flags: u32) -> u32;
}

#[link(name = "shell32")]
extern "system" {
    fn IsUserAnAdmin() -> i32;
    fn ShellExecuteExW(info: *mut ShellExecuteInfoW) -> i32;
}

#[link(name = "kernel32")]
extern "system" {
    fn WaitForSingleObject(handle: Handle, ms: u32) -> u32;
    fn GetExitCodeProcess(process: Handle, code: *mut u32) -> i32;
    fn CloseHandle(handle: Handle) -> i32;
    fn GetLastError() -> u32;
}

#[repr(C)]
struct ShellExecuteInfoW {
    cb_size: u32,
    f_mask: u32,
    hwnd: Handle,
    lp_verb: *const u16,
    lp_file: *const u16,
    lp_parameters: *const u16,
    lp_directory: *const u16,
    n_show: i32,
    h_inst_app: Handle,
    lp_idlist: Handle,
    lp_class: *const u16,
    hkey_class: Handle,
    dw_hotkey: u32,
    h_icon_or_mon: Handle,
    h_process: Handle,
}

const SEE_MASK_NOCLOSEPROCESS: u32 = 0x0000_0040;
const SEE_MASK_FLAG_NO_UI: u32 = 0x0000_0400;
const SW_SHOWNORMAL: i32 = 1;

/// What the machine currently thinks the instrument is.
#[derive(Debug, Clone, Default)]
pub struct Status {
    /// The device node exists (whatever driver owns it).
    pub found: bool,
    pub instance_id: Option<String>,
    pub description: Option<String>,
    pub class: Option<String>,
    /// Kernel service driving the node: `WinUSB`, `DSO6CDE`, …
    pub service: Option<String>,
    /// A non-zero code means the node is in an error state.
    pub problem: Option<u32>,
}

impl Status {
    /// True when the node is on WinUSB and healthy.
    pub fn is_winusb(&self) -> bool {
        self.found
            && self
                .service
                .as_deref()
                .map(|s| s.eq_ignore_ascii_case(WANT_SERVICE))
                .unwrap_or(false)
            && self.problem.unwrap_or(0) == 0
    }

    /// One line for the console and the UI.
    pub fn summary(&self) -> String {
        if !self.found {
            return "прибор не найден (USB 0783:5725)".into();
        }
        let service = self.service.as_deref().unwrap_or("?");
        if let Some(p) = self.problem.filter(|p| *p != 0) {
            return format!("прибор найден, но не работает (служба {service}, код {p})");
        }
        if self.is_winusb() {
            format!("прибор на WinUSB — готов к работе")
        } else {
            format!("прибор на службе {service} — нужен WinUSB")
        }
    }
}

fn wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(std::iter::once(0)).collect()
}

unsafe fn registry_string(set: Handle, info: *mut SpDevInfoData, property: u32) -> Option<String> {
    let mut buf = vec![0u8; 1024];
    let mut needed = 0u32;
    let ok = SetupDiGetDeviceRegistryPropertyW(
        set,
        info,
        property,
        ptr::null_mut(),
        buf.as_mut_ptr(),
        buf.len() as u32,
        &mut needed,
    );
    if ok == 0 {
        return None;
    }
    let units: Vec<u16> = buf
        .chunks_exact(2)
        .map(|c| u16::from_le_bytes([c[0], c[1]]))
        .take_while(|u| *u != 0)
        .collect();
    if units.is_empty() {
        None
    } else {
        Some(String::from_utf16_lossy(&units))
    }
}

/// Enumerate every present device node and keep the ones matching our IDs.
///
/// This deliberately looks at *all* device classes: the instrument is a plain
/// USB device under WinUSB, but a display-class node under Hantek's own driver,
/// and we must be able to describe both states.
pub fn status() -> Status {
    let mut out = Status::default();
    unsafe {
        let set = SetupDiGetClassDevsW(ptr::null(), ptr::null(), ptr::null_mut(), DIGCF_PRESENT | DIGCF_ALLCLASSES);
        if set.is_null() || set as isize == -1 {
            return out;
        }
        let mut index = 0u32;
        loop {
            let mut info = SpDevInfoData {
                cb_size: std::mem::size_of::<SpDevInfoData>() as u32,
                class_guid: Guid { data1: 0, data2: 0, data3: 0, data4: [0; 8] },
                dev_inst: 0,
                reserved: 0,
            };
            if SetupDiEnumDeviceInfo(set, index, &mut info) == 0 {
                break;
            }
            index += 1;

            // Hardware IDs are a REG_MULTI_SZ: the first entry is the most
            // specific, which is the one we are looking for.
            let mut ids = vec![0u8; 2048];
            let mut needed = 0u32;
            let ok = SetupDiGetDeviceRegistryPropertyW(
                set,
                &mut info,
                SPDRP_HARDWAREID,
                ptr::null_mut(),
                ids.as_mut_ptr(),
                ids.len() as u32,
                &mut needed,
            );
            if ok == 0 {
                continue;
            }
            let units: Vec<u16> = ids
                .chunks_exact(2)
                .map(|c| u16::from_le_bytes([c[0], c[1]]))
                .take_while(|u| *u != 0)
                .collect();
            let hay = String::from_utf16_lossy(&units).to_ascii_uppercase();
            if !hay.contains(VID_PID) {
                continue;
            }

            out.found = true;
            let mut idbuf = vec![0u16; 512];
            if SetupDiGetDeviceInstanceIdW(set, &mut info, idbuf.as_mut_ptr(), idbuf.len() as u32, ptr::null_mut()) != 0 {
                let len = idbuf.iter().position(|u| *u == 0).unwrap_or(0);
                out.instance_id = Some(String::from_utf16_lossy(&idbuf[..len]));
            }
            out.description = registry_string(set, &mut info, SPDRP_FRIENDLYNAME)
                .or_else(|| registry_string(set, &mut info, SPDRP_DEVICEDESC));
            out.class = registry_string(set, &mut info, SPDRP_CLASS);
            out.service = registry_string(set, &mut info, SPDRP_SERVICE);

            let mut status_flags = 0u32;
            let mut problem = 0u32;
            if CM_Get_DevNode_Status(&mut status_flags, &mut problem, info.dev_inst, 0) == 0 && problem != 0 {
                out.problem = Some(problem);
            }
            break;
        }
        SetupDiDestroyDeviceInfoList(set);
    }
    out
}

/// The strongest possible readiness signal: WinUSB hands us an interface path.
pub fn winusb_ready() -> bool {
    !hantek1008::transport::winusb::device_paths().is_empty()
}

/// Are we running with administrator rights?
pub fn is_admin() -> bool {
    unsafe { IsUserAnAdmin() != 0 }
}

/// Re-run this executable with the same arguments, elevated, and wait for it.
///
/// Used for anything that writes outside the user profile: driver install,
/// `install`, `uninstall`. The child is a copy of this very program, so the
/// UAC prompt names a binary the user already chose to run.
pub fn elevate_and_wait(args: &[String]) -> Result<i32, String> {
    let exe = std::env::current_exe().map_err(|e| format!("не удалось найти себя: {e}"))?;
    let params = args
        .iter()
        .map(|a| if a.contains(' ') { format!("\"{a}\"") } else { a.clone() })
        .collect::<Vec<_>>()
        .join(" ");
    let verb = wide("runas");
    let file = wide(&exe.to_string_lossy());
    let param_w = wide(&params);
    let dir = wide(&exe.parent().map(|p| p.to_string_lossy().into_owned()).unwrap_or_default());

    let mut info = ShellExecuteInfoW {
        cb_size: std::mem::size_of::<ShellExecuteInfoW>() as u32,
        f_mask: SEE_MASK_NOCLOSEPROCESS | SEE_MASK_FLAG_NO_UI,
        hwnd: ptr::null_mut(),
        lp_verb: verb.as_ptr(),
        lp_file: file.as_ptr(),
        lp_parameters: param_w.as_ptr(),
        lp_directory: dir.as_ptr(),
        n_show: SW_SHOWNORMAL,
        h_inst_app: ptr::null_mut(),
        lp_idlist: ptr::null_mut(),
        lp_class: ptr::null(),
        hkey_class: ptr::null_mut(),
        dw_hotkey: 0,
        h_icon_or_mon: ptr::null_mut(),
        h_process: ptr::null_mut(),
    };

    unsafe {
        if ShellExecuteExW(&mut info) == 0 {
            let err = GetLastError();
            // 1223 == the user pressed "No" on the UAC prompt.
            return Err(if err == 1223 {
                "повышение прав отменено пользователем".into()
            } else {
                format!("не удалось запустить себя с правами администратора (код {err})")
            });
        }
        if info.h_process.is_null() {
            return Err("процесс с повышенными правами не запустился".into());
        }
        WaitForSingleObject(info.h_process, u32::MAX);
        let mut code = 0u32;
        GetExitCodeProcess(info.h_process, &mut code);
        CloseHandle(info.h_process);
        Ok(code as i32)
    }
}

fn run(program: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(program)
        .args(args)
        .output()
        .map_err(|e| format!("не удалось запустить {program}: {e}"))?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok(text)
}

/// Install (or refresh) the WinUSB binding. Requires administrator rights.
///
/// Idempotent: on a machine where the package is already present the AddDriver
/// call answers "already exists" and the rescan simply re-binds the device.
pub fn install() -> Result<(), String> {
    if !is_admin() {
        return Err("для установки драйвера нужны права администратора".into());
    }

    let dir = std::env::temp_dir().join("davinci-driver");
    std::fs::create_dir_all(&dir).map_err(|e| format!("не удалось создать {}: {e}", dir.display()))?;
    let inf = dir.join("ydj-2088.inf");
    let cat = dir.join("YDJ-2088.cat");
    let cer = dir.join("davinci-libwdi.cer");
    std::fs::write(&inf, DRIVER_INF).map_err(|e| format!("INF: {e}"))?;
    std::fs::write(&cat, DRIVER_CAT).map_err(|e| format!("CAT: {e}"))?;
    std::fs::write(&cer, DRIVER_CER).map_err(|e| format!("сертификат: {e}"))?;

    // The catalog is self-signed, so the certificate has to be trusted at the
    // machine level before PnP will accept the package. Both stores are needed:
    // Root for chain building, TrustedPublisher for the install prompt policy.
    for store in ["Root", "TrustedPublisher"] {
        let out = run("certutil", &["-addstore", "-f", store, &cer.to_string_lossy()])?;
        if !out.contains("successfully") && !out.contains("успешно") && !out.contains("already") {
            // Not fatal on its own; the AddDriver step below is the real judge.
            eprintln!("  certutil {store}: {}", out.trim());
        }
    }

    let out = run("pnputil", &["/add-driver", &inf.to_string_lossy(), "/install"])?;
    print!("{}", indent(&out));

    let _ = run("pnputil", &["/scan-devices"])?;

    // Give PnP a moment, then judge by the only signal that matters.
    for _ in 0..20 {
        if winusb_ready() {
            return Ok(());
        }
        std::thread::sleep(std::time::Duration::from_millis(250));
    }
    Err(format!(
        "драйвер установлен, но устройство не отдало WinUSB-интерфейс.\n{}",
        status().summary()
    ))
}

fn indent(text: &str) -> String {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| format!("  {l}\n"))
        .collect()
}

/// Paths of the embedded driver package, so `doctor` can report digests.
pub fn package_sizes() -> (usize, usize, usize) {
    (DRIVER_INF.len(), DRIVER_CAT.len(), DRIVER_CER.len())
}

/// `davinci driver status` / `davinci driver install`.
pub fn cmd(args: &[String]) -> i32 {
    match args.first().map(String::as_str).unwrap_or("status") {
        "status" => {
            let st = status();
            println!("прибор    : {}", st.summary());
            if let Some(id) = &st.instance_id {
                println!("устройство: {id}");
            }
            println!("служба    : {}", st.service.as_deref().unwrap_or("—"));
            println!("класс     : {}", st.class.as_deref().unwrap_or("—"));
            println!("winusb    : {}", if winusb_ready() { "да" } else { "нет" });
            i32::from(!winusb_ready())
        }
        "install" => {
            if !is_admin() {
                let mut again = vec!["driver".to_string(), "install".to_string()];
                again.extend(args.iter().skip(1).cloned());
                return match elevate_and_wait(&again) {
                    Ok(code) => code,
                    Err(e) => {
                        eprintln!("{e}");
                        1
                    }
                };
            }
            match install() {
                Ok(()) => {
                    println!("готово: прибор на WinUSB");
                    0
                }
                Err(e) => {
                    eprintln!("{e}");
                    1
                }
            }
        }
        other => {
            eprintln!("неизвестное действие: {other}\n  davinci driver status | install");
            2
        }
    }
}
