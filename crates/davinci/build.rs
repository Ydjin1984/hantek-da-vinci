//! Bakes `ui/dist` into the binary.
//!
//! The shipped program is a single `.exe`: no `ui/` directory next to it, no
//! Node, no Python, nothing to forget. The build walks the Vite output once and
//! emits a `&[(name, bytes, mime)]` table that `src/assets.rs` includes.
//!
//! Keeping this in `build.rs` (instead of an `include_dir!`-style crate) means
//! the whole program still has *zero* third-party dependencies beyond what the
//! daemon already needed.

use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = manifest.join("../../ui/dist");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let target = out_dir.join("assets_generated.rs");

    println!("cargo:rerun-if-changed={}", dist.display());

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if dist.is_dir() {
        walk(&dist, &dist, &mut files);
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let mut src = String::new();
    src.push_str("// @generated by crates/davinci/build.rs — do not edit.\n");
    src.push_str("pub static FILES: &[(&str, &[u8], &str)] = &[\n");
    if files.is_empty() {
        // A missing UI build must not break `cargo build`; it must break loud
        // and obvious when the window opens instead.
        src.push_str(concat!(
            "    (\"index.html\", b\"<!doctype html><meta charset=utf-8>",
            "<title>\\u041e\\u0441\\u0446\\u0438\\u043b\\u043b\\u043e\\u0433\\u0440\\u0430\\u0444 \\u0434\\u0430 \\u0412\\u0438\\u043d\\u0447\\u0438</title>",
            "<body style=\\\"font:16px system-ui;background:#0b0f14;color:#d7e3ee;padding:40px\\\">",
            "<h1>\\u0418\\u043d\\u0442\\u0435\\u0440\\u0444\\u0435\\u0439\\u0441 \\u043d\\u0435 \\u0441\\u043e\\u0431\\u0440\\u0430\\u043d</h1>",
            "<p>\\u0421\\u043e\\u0431\\u0435\\u0440\\u0438\\u0442\\u0435 \\u0435\\u0433\\u043e: <code>cd ui &amp;&amp; npm ci &amp;&amp; npm run build</code>, \\u0437\\u0430\\u0442\\u0435\\u043c \\u043f\\u0435\\u0440\\u0435\\u0441\\u043e\\u0431\\u0435\\u0440\\u0438\\u0442\\u0435 </p>",
            "<pre>cargo build --release</pre></body>\", \"text/html; charset=utf-8\"),\n"
        ));
    }
    for (rel, path) in &files {
        src.push_str(&format!(
            "    ({:?}, include_bytes!({:?}), {:?}),\n",
            rel,
            path.to_string_lossy(),
            mime_for(rel)
        ));
        println!("cargo:rerun-if-changed={}", path.display());
    }
    src.push_str("];\n");

    std::fs::write(&target, src).expect("write generated assets");
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(root, &path, out);
        } else if path.is_file() {
            if let Ok(rel) = path.strip_prefix(root) {
                let name = rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
                out.push((name, path.clone()));
            }
        }
    }
}

fn mime_for(name: &str) -> &'static str {
    let ext = name.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
    match ext.as_str() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
